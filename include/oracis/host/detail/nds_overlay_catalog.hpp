/*
 * Strict reader for the local overlay extraction manifest.
 *
 * The catalog is metadata-only. It never executes guest code, applies
 * relocations, or changes guest memory. Image bytes are opened and hashed
 * only when a specific CPU/overlay pair is requested.
 */
#ifndef ORACIS_HOST_DETAIL_NDS_OVERLAY_CATALOG_HPP
#define ORACIS_HOST_DETAIL_NDS_OVERLAY_CATALOG_HPP

#include <cstdint>
#include <filesystem>
#include <string>
#include <string_view>
#include <vector>

#include "oracis/memory/guest_memory.hpp"

namespace oracis::host::detail {

enum class NdsOverlayCatalogStatus : uint8_t {
    Ok = 0,
    Missing,
    IoError,
    InvalidManifest,
    RomIdentityMismatch,
    OverlayNotFound,
    ImageMissing,
    ImageInvalid,
    ImageHashMismatch
};

struct NdsOverlayCatalogRecord {
    NdsCpu cpu = NDS_ARM9;
    uint32_t overlay_id = 0u;
    uint32_t ram_address = 0u;
    uint32_t ram_size = 0u;
    uint32_t bss_size = 0u;
    uint32_t static_init_start = 0u;
    uint32_t static_init_end = 0u;
    uint32_t image_size = 0u;
    std::string image_file;
    std::string image_sha1;
};

class NdsOverlayCatalog final {
public:
    static constexpr uint32_t MaxManifestBytes = 8u * 1024u * 1024u;
    static constexpr uint32_t MaxOverlayImageBytes = 16u * 1024u * 1024u;
    static constexpr uint32_t MaxOverlayRecords = 4096u;

    NdsOverlayCatalog() = default;

    /*
     * Open a manifest generated by extract_nds_overlays.py. The manifest ROM
     * identity must match expected_rom_sha1. On failure, out is unchanged.
     */
    static NdsOverlayCatalogStatus open(
        const std::filesystem::path &directory,
        std::string_view expected_rom_sha1,
        NdsOverlayCatalog &out,
        std::string *diagnostic = nullptr) noexcept;

    const NdsOverlayCatalogRecord *find(
        NdsCpu cpu, uint32_t overlay_id) const noexcept;

    /*
     * Read one already-decompressed image. The file name is fixed by CPU and
     * overlay ID, the file must be a regular non-symlink file of exact size,
     * and its SHA-1 must match the verified manifest record.
     */
    NdsOverlayCatalogStatus read_image(
        const NdsOverlayCatalogRecord &record,
        std::vector<uint8_t> &contents,
        std::string *diagnostic = nullptr) const noexcept;

    const std::vector<NdsOverlayCatalogRecord> &records() const noexcept
    {
        return records_;
    }

    const std::filesystem::path &directory() const noexcept
    {
        return directory_;
    }

private:
    std::filesystem::path directory_;
    std::vector<NdsOverlayCatalogRecord> records_;
};

const char *nds_overlay_catalog_status_name(
    NdsOverlayCatalogStatus status) noexcept;

} // namespace oracis::host::detail

#endif /* ORACIS_HOST_DETAIL_NDS_OVERLAY_CATALOG_HPP */
